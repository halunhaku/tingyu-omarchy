#requires -version 5.1
<#
.SYNOPSIS
  Drives the real Tingyu Windows window and records what happened.

.DESCRIPTION
  This is the W0 evidence for "the window is real": it starts build\tingyu.exe
  with a fresh data directory whose name contains Chinese characters and a
  space, waits for the scan, then uses UI Automation to:

    * read the window title, visibility and client size;
    * invoke the real "播放全部" button (the same click path a person uses)
      and wait for the app log to report a play request and a first sound;
    * switch pages through the sidebar and prove the rendered window changed;
    * close the window with WindowPattern.Close and wait for the process to
      exit, then check the log, the exit code and that library.sqlite is no
      longer locked.

  It writes <Out>\window-report.json plus screenshots and exits non-zero if
  any step fails. It does not read personal media: the WAV is generated by
  w0accept.exe.
#>
param(
  [string]$Mpv = "",
  [string]$Out = "",
  [string]$Go = ""
)
$ErrorActionPreference = "Stop"
$ProgressPreference = "SilentlyContinue"

$client = (Resolve-Path (Join-Path $PSScriptRoot "..")).Path
$build = Join-Path $client "build"
if (-not $Mpv) { $Mpv = Join-Path $build "mpv\libmpv-2.dll" }
if (-not $Out) { $Out = Join-Path $build "w0-evidence\window" }
if (-not $Go) {
  if ($env:GO) { $Go = $env:GO }
  elseif (Test-Path "G:\tingyu-windows-tools\go\bin\go.exe") { $Go = "G:\tingyu-windows-tools\go\bin\go.exe" }
}

$root = Join-Path $build "w0-window"
$data = Join-Path $root "听屿 数据"
$media = Join-Path $root "媒体 目录"
$log = Join-Path $root "window.log"
$exitFile = Join-Path $build "exit-code.txt"
$w0accept = Join-Path $build "w0accept.exe"
$exe = Join-Path $build "tingyu.exe"
New-Item -ItemType Directory -Force -Path $Out | Out-Null

if (-not (Test-Path $w0accept)) { throw "missing $w0accept; run scripts\windows-build.ps1 first" }
if (-not (Test-Path $exe)) { throw "missing $exe; run scripts\windows-build.ps1 first" }
if (-not (Test-Path $Mpv)) { throw "missing $Mpv; run scripts\windows-setup.ps1 first" }

# A batch wrapper records the GUI process's exit code; Start-Process on its
# own does not expose it reliably here.
$wrapper = Join-Path $build "run-tingyu.cmd"
Set-Content -Path $wrapper -Encoding ASCII -Value @(
  '@echo off',
  '"%~dp0tingyu.exe"',
  '> "%~dp0exit-code.txt" echo %ERRORLEVEL%'
)

# --- helpers --------------------------------------------------------

Add-Type -AssemblyName System.Drawing
Add-Type -AssemblyName UIAutomationClient, UIAutomationTypes
Add-Type @"
using System;
using System.Runtime.InteropServices;
public class W0Win {
  [StructLayout(LayoutKind.Sequential)] public struct RECT { public int Left, Top, Right, Bottom; }
  [DllImport("user32.dll")] public static extern bool GetWindowRect(IntPtr hwnd, out RECT r);
  [DllImport("user32.dll")] public static extern bool GetClientRect(IntPtr hwnd, out RECT r);
  [DllImport("user32.dll")] public static extern bool IsWindowVisible(IntPtr hwnd);
  [DllImport("user32.dll")] public static extern uint GetDpiForWindow(IntPtr hwnd);
  [DllImport("user32.dll")] public static extern bool PrintWindow(IntPtr hwnd, IntPtr hdc, uint flags);
  [DllImport("user32.dll")] public static extern bool PostMessage(IntPtr hwnd, uint msg, IntPtr w, IntPtr l);
}
"@

$script:results = @()
function Test-Step([string]$Name, [string]$Expected, [scriptblock]$Fn) {
  $sw = [Diagnostics.Stopwatch]::StartNew()
  try {
    $actual = & $Fn
    $ok = $true
  } catch {
    $actual = $_.Exception.Message
    $ok = $false
  }
  $sw.Stop()
  $script:results += [pscustomobject]@{
    name = $Name; expected = $Expected; ok = $ok
    actual = [string]$actual; elapsed = "$($sw.ElapsedMilliseconds)ms"
  }
  Write-Host ("[{0}] {1}: {2}" -f $(if ($ok) { "PASS" } else { "FAIL" }), $Name, $actual)
}

function Capture([IntPtr]$Handle, [string]$Path) {
  $r = New-Object W0Win+RECT
  [void][W0Win]::GetWindowRect($Handle, [ref]$r)
  $w = $r.Right - $r.Left; $h = $r.Bottom - $r.Top
  if ($w -le 0 -or $h -le 0) { throw "window rect ${w}x${h}" }
  $bmp = New-Object System.Drawing.Bitmap $w, $h
  $g = [System.Drawing.Graphics]::FromImage($bmp)
  $hdc = $g.GetHdc()
  $ok = [W0Win]::PrintWindow($Handle, $hdc, 2)
  $g.ReleaseHdc($hdc); $g.Dispose()
  $bmp.Save($Path, [System.Drawing.Imaging.ImageFormat]::Png)
  $bmp.Dispose()
  if (-not $ok) { throw "PrintWindow failed" }
  return "$w x $h"
}

function Find-Element($Root, [string]$Name, $ControlType) {
  $conditions = New-Object System.Collections.Generic.List[System.Windows.Automation.Condition]
  $conditions.Add((New-Object System.Windows.Automation.PropertyCondition([System.Windows.Automation.AutomationElement]::NameProperty, $Name)))
  if ($ControlType) {
    $conditions.Add((New-Object System.Windows.Automation.PropertyCondition([System.Windows.Automation.AutomationElement]::ControlTypeProperty, $ControlType)))
  }
  $cond = New-Object System.Windows.Automation.AndCondition($conditions.ToArray())
  return $Root.FindFirst([System.Windows.Automation.TreeScope]::Descendants, $cond)
}

function Find-ElementLike($Root, [string]$Pattern, $ControlType) {
  $all = $Root.FindAll([System.Windows.Automation.TreeScope]::Descendants, [System.Windows.Automation.Condition]::TrueCondition)
  foreach ($el in $all) {
    $name = $el.Current.Name
    if ($name -like $Pattern -and (-not $ControlType -or $el.Current.ControlType -eq $ControlType)) { return $el }
  }
  return $null
}

function Invoke-Element($Element) {
  $pattern = $Element.GetCurrentPattern([System.Windows.Automation.InvokePattern]::Pattern)
  $pattern.Invoke()
}

function Wait-Log([string]$Path, [string]$Pattern, [int]$TimeoutSeconds) {
  $deadline = (Get-Date).AddSeconds($TimeoutSeconds)
  while ((Get-Date) -lt $deadline) {
    if (Test-Path $Path) {
      $match = Select-String -Path $Path -Encoding UTF8 -Pattern $Pattern -ErrorAction SilentlyContinue | Select-Object -First 1
      if ($match) { return $match.Line }
    }
    Start-Sleep -Milliseconds 200
  }
  throw "log line '$Pattern' not found in $Path within ${TimeoutSeconds}s"
}

# --- run ------------------------------------------------------------

Remove-Item -Recurse -Force $root -ErrorAction SilentlyContinue
New-Item -ItemType Directory -Force -Path $data, $media | Out-Null
& $w0accept -wav (Join-Path $media "测试 音频.wav") | Out-Null
if ($LASTEXITCODE -ne 0) { throw "w0accept -wav failed" }

Remove-Item -Force $exitFile -ErrorAction SilentlyContinue
$before = @(Get-Process tingyu -ErrorAction SilentlyContinue | ForEach-Object Id)

$env:TINGYU_DATA_DIR = $data
$env:TINGYU_AUTO_SCAN_DIR = $media
$env:TINGYU_STARTUP_LOG = $log
$env:TINGYU_AUTO_QUIT_MS = ""
Remove-Item -Force $log -ErrorAction SilentlyContinue

$console = Start-Process -FilePath "cmd.exe" -ArgumentList "/c", "`"$wrapper`"" -WindowStyle Hidden -PassThru
$proc = $null
$hwnd = [IntPtr]::Zero
$deadline = (Get-Date).AddSeconds(20)
while ((Get-Date) -lt $deadline) {
  $proc = Get-Process tingyu -ErrorAction SilentlyContinue | Where-Object { $before -notcontains $_.Id } | Select-Object -First 1
  if ($proc) {
    $proc.Refresh()
    if ($proc.MainWindowHandle -ne [IntPtr]::Zero) { $hwnd = $proc.MainWindowHandle; break }
  }
  Start-Sleep -Milliseconds 200
}
if (-not $proc -or $hwnd -eq [IntPtr]::Zero) {
  throw "tingyu.exe window did not appear within 20 s (log: $log)"
}
$uiRoot = [System.Windows.Automation.AutomationElement]::FromHandle($hwnd)
$pidOfApp = $proc.Id
Write-Host "started tingyu pid=$pidOfApp hwnd=$hwnd"

try {
  Test-Step "window-visible" "a visible window titled 听屿 with at least the 900x600 minimum client area (DPI-scaled)" {
    $title = $uiRoot.Current.Name
    if (-not [W0Win]::IsWindowVisible($hwnd)) { throw "window is not visible" }
    $r = New-Object W0Win+RECT
    [void][W0Win]::GetClientRect($hwnd, [ref]$r)
    $w = $r.Right - $r.Left; $h = $r.Bottom - $r.Top
    $dpi = [W0Win]::GetDpiForWindow($hwnd)
    $scale = [math]::Round($dpi / 96.0, 2)
    if ($title -ne "听屿") { throw "window title '$title'" }
    if ($w -lt 900 -or $h -lt 600) { throw "client area ${w}x${h} is below the 900x600 minimum" }
    "title=$title visible=true client=${w}x${h} dpi=$dpi scale=$scale"
  }

  Test-Step "scan-rendered" "the scanned track is visible in the library list" {
    $deadline = (Get-Date).AddSeconds(20)
    $row = $null
    while ((Get-Date) -lt $deadline) {
      $row = Find-ElementLike $uiRoot "*测试 音频*" ([System.Windows.Automation.ControlType]::ListItem)
      if ($row) { break }
      Start-Sleep -Milliseconds 300
    }
    if (-not $row) { throw "scanned track row not found in the accessibility tree" }
    $before = Join-Path $Out "window-before.png"
    $size = Capture $hwnd $before
    "row='$($row.Current.Name)' screenshot=$before ($size)"
  }

  Test-Step "play-click" "clicking 播放全部 starts playback and the log reports sound" {
    $button = Find-Element $uiRoot "播放全部" ([System.Windows.Automation.ControlType]::Button)
    if (-not $button) { throw "播放全部 button not found" }
    Invoke-Element $button
    $request = Wait-Log $log "play: request" 10
    $sound = Wait-Log $log "play: sound after" 10
    "$request | $sound"
  }

  Test-Step "nav-click" "clicking the 搜索 item changes the rendered window" {
    $before = Join-Path $Out "window-before-nav.png"
    $after = Join-Path $Out "window-after-nav.png"
    [void](Capture $hwnd $before)
    $search = Find-Element $uiRoot "搜索" ([System.Windows.Automation.ControlType]::Button)
    if (-not $search) { throw "sidebar 搜索 button not found" }
    Invoke-Element $search
    Start-Sleep -Milliseconds 1200
    [void](Capture $hwnd $after)
    $h1 = (Get-FileHash $before -Algorithm SHA256).Hash
    $h2 = (Get-FileHash $after -Algorithm SHA256).Hash
    if ($h1 -eq $h2) { throw "window pixels did not change after the click" }
    $library = Find-ElementLike $uiRoot "曲库*" ([System.Windows.Automation.ControlType]::Button)
    if ($library) { Invoke-Element $library; Start-Sleep -Milliseconds 500 }
    "screenshot changed ($($h1.Substring(0,12)) -> $($h2.Substring(0,12)))"
  }

  Test-Step "window-close" "closing the window quits the process with exit code 0" {
    $closed = $false
    try {
      $windowPattern = $uiRoot.GetCurrentPattern([System.Windows.Automation.WindowPattern]::Pattern)
      $windowPattern.Close()
      $closed = $true
    } catch {
      [void][W0Win]::PostMessage($hwnd, 0x0010, [IntPtr]::Zero, [IntPtr]::Zero)
    }
    $deadline = (Get-Date).AddSeconds(20)
    while ((Get-Date) -lt $deadline) {
      if (-not (Get-Process -Id $pidOfApp -ErrorAction SilentlyContinue)) { break }
      Start-Sleep -Milliseconds 200
    }
    if (Get-Process -Id $pidOfApp -ErrorAction SilentlyContinue) { throw "process still running 20 s after close" }
    if (-not (Test-Path $exitFile)) { throw "exit code file not written" }
    $code = (Get-Content $exitFile -Raw).Trim()
    if ($code -ne "0") { throw "exit code $code, want 0" }
    "closedVia=$($(if ($closed) {'WindowPattern'} else {'WM_CLOSE'})) exit=$code"
  }

  Test-Step "shutdown-log" "the engine, session and library are closed at exit" {
    $quit = Wait-Log $log "app: quit complete" 5
    $engine = Wait-Log $log "playback: engine closed" 5
    $session = Wait-Log $log "session: now playing cleared" 5
    $closed = Wait-Log $log "window: closed" 5
    "$quit | $engine | $session | $closed"
  }

  Test-Step "library-unlocked" "library.sqlite is not held open after exit" {
    $lib = Join-Path $data "library.sqlite"
    if (-not (Test-Path $lib)) { throw "library.sqlite missing at $lib" }
    Move-Item -LiteralPath $lib -Destination "$lib.moved"
    Move-Item -LiteralPath "$lib.moved" -Destination $lib
    "renamed and restored $lib"
  }
} finally {
  if ($proc -and (Get-Process -Id $proc.Id -ErrorAction SilentlyContinue)) {
    Stop-Process -Id $proc.Id -Force -ErrorAction SilentlyContinue
  }
  if ($console -and -not $console.HasExited) { Stop-Process -Id $console.Id -Force -ErrorAction SilentlyContinue }
  $env:TINGYU_DATA_DIR = ""
  $env:TINGYU_AUTO_SCAN_DIR = ""
  $env:TINGYU_STARTUP_LOG = ""
}

$ok = ($script:results | Where-Object { -not $_.ok }).Count -eq 0
$report = [pscustomobject]@{
  ok = $ok
  platform = "windows/amd64"
  dataDir = $data
  mediaDir = $media
  log = $log
  steps = $script:results
}
$reportPath = Join-Path $Out "window-report.json"
$report | ConvertTo-Json -Depth 6 | Set-Content -Path $reportPath -Encoding UTF8
Write-Host ""
Write-Host "report: $reportPath"
if (-not $ok) { exit 1 }
